export function getSchool(id: string): School | undefined {
  return SCHOOLS.find((s) => s.id === id);
}

export function getProgram(id: string): Program | undefined {
  return PROGRAMS.find((p) => p.id === id);
}

export function getCareer(id: string): Career | undefined {
  return CAREERS.find((c) => c.id === id);
}

export function getPathway(id: string): Pathway | undefined {
  return PATHWAYS.find((p) => p.id === id);
}

export function getProgramsForSchool(schoolId: string): Program[] {
  return PROGRAMS.filter((p) => p.schoolId === schoolId);
}

export function getPathwaysForCareer(careerId: string): Pathway[] {
  return PATHWAYS.filter((p) => p.careerIds.includes(careerId));
}

export function getPathwaysForSchool(schoolId: string): Pathway[] {
  return PATHWAYS.filter((p) => p.schoolIds.includes(schoolId));
}

export function getPathwaysForProgram(programId: string): Pathway[] {
  return PATHWAYS.filter((p) => p.steps.some((step) => step.refId === programId));
}

export function getCareersByField(field: Field): Career[] {
  return CAREERS.filter((c) => c.field === field);
}
